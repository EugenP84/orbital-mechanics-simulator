package io.github.eugenp84.orbitalsim.core.physics;

import io.github.eugenp84.orbitalsim.core.math.PhysicalConstants;
import io.github.eugenp84.orbitalsim.core.math.StateVector;
import io.github.eugenp84.orbitalsim.core.math.Vector3D;

import java.util.Objects;

/**
 * Computes the mechanical energy of a gravitational system.
 * <p>
 * Kinetic energy is summed per body and gravitational potential energy over
 * unique pairs:
 * <pre>
 *     E = Σᵢ ½ mᵢ vᵢ²  −  Σᵢ&lt;ⱼ G mᵢ mⱼ / rᵢⱼ
 * </pre>
 * Zero potential is taken at infinite separation, following standard
 * astrodynamics convention (Bate, Mueller and White, 1971; Curtis, 2024).
 * <p>
 * <strong>Validity.</strong> The total returned by this class is a conserved
 * invariant only for a <em>fully coupled</em> Newtonian system, in which every
 * body acts gravitationally on every other. In the restricted configuration
 * used by the NEO scenario, where a finite-mass body's back-reaction on the
 * primaries is deliberately omitted, the implemented equations are not those
 * of a closed system generated by a symmetric pair potential, and the
 * expression above is not an invariant of them (ADR-004).
 * <p>
 * This constraint is not enforced here. Interaction policy is held by the
 * aggregation configuration, and importing it into a physics primitive would
 * reintroduce scenario-specific concerns that ADR-003 and ADR-004 deliberately
 * placed elsewhere. Callers are responsible for applying these methods only to
 * fully coupled configurations when reporting conservation results.
 * <p>
 * Energy is frame-dependent: a system whose centre of mass translates carries
 * a constant bulk kinetic term. Comparison scenarios are initialised in the
 * centre-of-mass inertial frame and energies computed in that fixed frame,
 * rather than by re-centring at each step, so that numerical drift remains
 * observable (ADR-003, Notes for Evaluation).
 * <p>
 * Empty systems are permitted: the system-level methods return zero for an
 * empty array, which is the correct empty sum and avoids requiring callers to
 * special-case body count before invoking them.
 * <p>
 * All quantities are in canonical SI units: energies in joules. The class is
 * stateless and its methods are pure functions of their arguments. Inputs are
 * validated independently of invariants guaranteed elsewhere.
 */
public final class EnergyCalculator {

    private EnergyCalculator() {
        // Stateless utility — not instantiable
    }

    /**
     * Kinetic energy of a single body, ½mv².
     *
     * @param mass     mass in kilograms; must be positive and finite
     * @param velocity velocity in m·s⁻¹
     * @return kinetic energy in joules
     * @throws NullPointerException     if {@code velocity} is null
     * @throws IllegalArgumentException if the mass is not positive and finite,
     *         or if the result is not finite
     */
    public static double kineticEnergy(double mass, Vector3D velocity) {
        Objects.requireNonNull(velocity, "velocity must not be null");
        requirePositiveFiniteMass(mass, "Mass");

        double energy = 0.5 * mass * velocity.magnitudeSquared();
        requireFinite(energy, "Kinetic energy");
        return energy;
    }

    /**
     * Gravitational potential energy of a pair of masses, −Gm₁m₂/r.
     * <p>
     * The value is negative for any finite positive separation, since zero
     * potential is defined at infinite separation. Whether a system is
     * gravitationally bound depends on its total mechanical energy, not on the
     * sign of the potential term alone.
     *
     * @param massA    first mass in kilograms; must be positive and finite
     * @param massB    second mass in kilograms; must be positive and finite
     * @param distance separation in metres; must be positive and finite
     * @return potential energy in joules, always negative
     * @throws IllegalArgumentException if any argument is not positive and
     *         finite, or if the result is not finite
     */
    public static double potentialEnergy(double massA, double massB, double distance) {
        requirePositiveFiniteMass(massA, "First mass");
        requirePositiveFiniteMass(massB, "Second mass");

        if (distance <= 0.0 || !Double.isFinite(distance)) {
            throw new IllegalArgumentException(
                    "Separation must be positive and finite, was: " + distance);
        }

        double energy = -PhysicalConstants.GRAVITATIONAL_CONSTANT * massA * massB / distance;
        requireFinite(energy, "Potential energy");
        return energy;
    }

    /**
     * Total kinetic energy of a system.
     *
     * @param masses masses in kilograms, each positive and finite
     * @param states corresponding states; must be the same length as
     *               {@code masses}
     * @return total kinetic energy in joules; zero for an empty system
     * @throws NullPointerException     if either array or any state is null
     * @throws IllegalArgumentException if the lengths differ, if any mass is
     *         not positive and finite, or if the result is not finite
     */
    public static double totalKineticEnergy(double[] masses, StateVector[] states) {
        requireValidSystemInputs(masses, states);

        double total = 0.0;
        for (int i = 0; i < masses.length; i++) {
            total += kineticEnergy(masses[i], states[i].velocity());
        }

        requireFinite(total, "Total kinetic energy");
        return total;
    }

    /**
     * Total gravitational potential energy of a system, summed over unique
     * pairs.
     * <p>
     * Each interaction is counted exactly once (i &lt; j). Summing over all
     * ordered pairs would double the magnitude while remaining internally
     * self-consistent over time, and would therefore not be apparent from a
     * conservation plot alone (ADR-003, Notes for Evaluation).
     *
     * @param masses masses in kilograms, each positive and finite
     * @param states corresponding states; must be the same length as
     *               {@code masses}
     * @return total potential energy in joules, negative for any system of two
     *         or more bodies; zero for an empty or single-body system, which
     *         contain no gravitational pairs
     * @throws NullPointerException     if either array or any state is null
     * @throws IllegalArgumentException if the lengths differ, if any mass is
     *         not positive and finite, if any two bodies coincide, or if the
     *         result is not finite
     */
    public static double totalPotentialEnergy(double[] masses, StateVector[] states) {
        requireValidSystemInputs(masses, states);

        double total = 0.0;
        for (int i = 0; i < masses.length; i++) {
            for (int j = i + 1; j < masses.length; j++) {
                double distance = states[i].position().distanceTo(states[j].position());
                total += potentialEnergy(masses[i], masses[j], distance);
            }
        }

        requireFinite(total, "Total potential energy");
        return total;
    }

    /**
     * Total mechanical energy of a system: kinetic plus potential.
     * <p>
     * Conserved only for fully coupled systems; see the class documentation.
     *
     * @param masses masses in kilograms, each positive and finite
     * @param states corresponding states; must be the same length as
     *               {@code masses}
     * @return total mechanical energy in joules; zero for an empty system
     * @throws NullPointerException     if either array or any state is null
     * @throws IllegalArgumentException if the inputs are invalid or the result
     *         is not finite
     */
    public static double totalMechanicalEnergy(double[] masses, StateVector[] states) {
        double total = totalKineticEnergy(masses, states)
                + totalPotentialEnergy(masses, states);

        requireFinite(total, "Total mechanical energy");
        return total;
    }

    /**
     * Validates the system-level contract: matched non-null arrays, non-null
     * states, and a positive finite mass for every body.
     * <p>
     * Masses are validated here rather than only where they are consumed,
     * because a body may not participate in any pair — a single-body system
     * never enters the pair loop — and the contract must hold regardless of
     * body count.
     */
    private static void requireValidSystemInputs(double[] masses, StateVector[] states) {
        Objects.requireNonNull(masses, "masses must not be null");
        Objects.requireNonNull(states, "states must not be null");

        if (masses.length != states.length) {
            throw new IllegalArgumentException(
                    "masses and states must have equal length, were: "
                            + masses.length + " and " + states.length);
        }

        for (int i = 0; i < states.length; i++) {
            Objects.requireNonNull(states[i], "state at index " + i + " must not be null");
            requirePositiveFiniteMass(masses[i], "Mass at index " + i);
        }
    }

    private static void requirePositiveFiniteMass(double mass, String label) {
        if (mass <= 0.0 || !Double.isFinite(mass)) {
            throw new IllegalArgumentException(
                    label + " must be positive and finite, was: " + mass);
        }
    }

    private static void requireFinite(double value, String label) {
        if (!Double.isFinite(value)) {
            throw new IllegalArgumentException(label + " is not finite: " + value);
        }
    }
}